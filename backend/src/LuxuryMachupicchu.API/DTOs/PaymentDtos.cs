using System.ComponentModel.DataAnnotations;

namespace LuxuryMachupicchu.API.DTOs;

public class CulqiConfigDto
{
    public string PublicKey { get; set; } = string.Empty;
    public string CurrencyDefault { get; set; } = "USD";
    public string BusinessName { get; set; } = "Luxury Machupicchu Peru";
}

public class CulqiChargeRequestDto
{
    [Required]
    public string TokenId { get; set; } = string.Empty; // Token generated by Culqi Checkout v4: tkn_test_...

    [Required]
    [EmailAddress]
    public string Email { get; set; } = string.Empty;

    [Required]
    [Range(1, 1000000)]
    public decimal Amount { get; set; } // Normal units, e.g. 2150.00 USD or 500.00 PEN

    [Required]
    public string Currency { get; set; } = "USD"; // USD or PEN

    public int? BookingId { get; set; }
    public int? ConciergeRequestId { get; set; }
    public string? CustomerName { get; set; }
    public string? CustomerPhone { get; set; }
    public string? ReferenceCode { get; set; }
    public string? Description { get; set; }
    public bool IsDepositOnly { get; set; } = false;
}

public class CulqiChargeResponseDto
{
    public bool Success { get; set; }
    public string ChargeId { get; set; } = string.Empty;
    public string AuthorizationCode { get; set; } = string.Empty;
    public decimal Amount { get; set; }
    public string Currency { get; set; } = "USD";
    public string CardBrand { get; set; } = string.Empty;
    public string CardLastFour { get; set; } = string.Empty;
    public string Status { get; set; } = string.Empty;
    public string Message { get; set; } = string.Empty;
    public DateTime TransactionDate { get; set; } = DateTime.UtcNow;
    public int? BookingId { get; set; }
    public string? ReferenceCode { get; set; }
}

public class PaymentTransactionDto
{
    public int Id { get; set; }
    public string CulqiChargeId { get; set; } = string.Empty;
    public string CulqiAuthorizationCode { get; set; } = string.Empty;
    public string ReferenceType { get; set; } = string.Empty;
    public string ReferenceCode { get; set; } = string.Empty;
    public int? BookingId { get; set; }
    public string CustomerName { get; set; } = string.Empty;
    public string CustomerEmail { get; set; } = string.Empty;
    public string CustomerPhone { get; set; } = string.Empty;
    public decimal Amount { get; set; }
    public string Currency { get; set; } = string.Empty;
    public string PaymentMethod { get; set; } = string.Empty;
    public string CardBrand { get; set; } = string.Empty;
    public string CardLastFour { get; set; } = string.Empty;
    public string Status { get; set; } = string.Empty;
    public DateTime CreatedAt { get; set; }
}

public class DepositPreferenceRequest
{
    public int TourId { get; set; }
    public string TourTitle { get; set; } = string.Empty;
    public decimal TotalAmount { get; set; }
    public string Currency { get; set; } = "USD";
    public string GuestEmail { get; set; } = string.Empty;
    public int? BookingId { get; set; }
}

public class CulqiWebhookResponseDto
{
    public bool Success { get; set; }
    public string Message { get; set; } = string.Empty;
    public string EventType { get; set; } = string.Empty;
    public string? ChargeId { get; set; }
    public string? ReferenceCode { get; set; }
    public string? BookingStatus { get; set; }
}
